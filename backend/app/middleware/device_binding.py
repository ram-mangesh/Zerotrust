"""Device Binding & Anti-Session-Hijack Middleware.

Enforces WebCrypto ECDSA P-256 hardware-bound cryptographic signatures:
  1. Verifies request signature freshness (30-second window against replay attacks).
  2. Cryptographically verifies ECDSA P-256 signature generated by browser WebCrypto API.
  3. Anti-Session Hijack: Compares request's public key against the public key
     registered during device authentication. If a stolen session token is used
     from another machine without the non-extractable private key, access is
     immediately rejected as `session_hijack`.
"""

from __future__ import annotations

import logging
import time
import uuid

from fastapi import Request
from fastapi.responses import JSONResponse
from sqlalchemy import select
from starlette.middleware.base import BaseHTTPMiddleware

from app.core import jwt as jwt_service
from app.core.database import get_session_factory
from app.core.ecdsa_verify import verify_ecdsa_signature
from app.middleware.context import client_ip
from app.models.alert import Alert
from app.models.enums import AlertSeverity, AlertStatus, SessionStatus
from app.models.session import UserSession

logger = logging.getLogger(__name__)

SIGNATURE_MAX_AGE_MS = 30000  # 30 seconds freshness window

EXEMPT_PREFIXES = (
    "/health",
    "/ready",
    "/docs",
    "/redoc",
    "/openapi.json",
    "/favicon.ico",
    "/static",
    "/api/auth/login",
    "/api/auth/mfa",
    "/api/auth/oauth",
    "/api/auth/register",
    "/voice/",
)


def _is_exempt(path: str) -> bool:
    return any(path.startswith(p) for p in EXEMPT_PREFIXES)


def _get_db_session(request: Request | None = None):
    if request is not None and hasattr(request, "app"):
        factory_override = getattr(request.app, "dependency_overrides", {}).get(
            get_session_factory
        )
        if factory_override is not None:
            return factory_override()()
    return get_session_factory()()


class DeviceBindingMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next):
        path = request.url.path

        if _is_exempt(path) or request.method == "OPTIONS":
            return await call_next(request)

        sig = request.headers.get("X-Device-Signature") or request.headers.get("x-zw-signature")
        ts = request.headers.get("X-Device-Timestamp") or request.headers.get("x-zw-timestamp")
        pubkey = request.headers.get("X-Device-Pubkey") or request.headers.get("x-zw-pubkey")

        # ── 1. Signature Freshness Check ──────────────────────────────────────
        if ts:
            try:
                ts_int = int(ts)
                now_ms = int(time.time() * 1000)
                if abs(now_ms - ts_int) > SIGNATURE_MAX_AGE_MS:
                    logger.warning("Device signature expired | path=%s drift=%dms", path, abs(now_ms - ts_int))
                    return JSONResponse(
                        status_code=401,
                        content={
                            "detail": "Device signature expired (replay window exceeded).",
                            "code": "signature_expired",
                        },
                        headers={"X-Device-Binding": "EXPIRED"},
                    )
            except ValueError:
                return JSONResponse(
                    status_code=401,
                    content={"detail": "Invalid device timestamp header.", "code": "invalid_timestamp"},
                )

        # ── 2. Cryptographic Signature Verification ───────────────────────────
        if sig and ts and pubkey:
            message = f"{request.method.upper()}:{path}:{ts}"
            is_valid = verify_ecdsa_signature(pubkey, message, sig)
            if not is_valid:
                logger.warning("Invalid ECDSA device signature on %s from %s", path, client_ip(request))
                return JSONResponse(
                    status_code=401,
                    content={
                        "detail": "Invalid cryptographic device signature.",
                        "code": "invalid_device_signature",
                    },
                    headers={"X-Device-Binding": "INVALID"},
                )

        # ── 3. Anti-Session Hijack Gate ───────────────────────────────────────
        # If bearer token is provided, verify pubkey matches registered session pubkey
        auth_hdr = request.headers.get("Authorization", "")
        if auth_hdr.lower().startswith("bearer ") and pubkey:
            token = auth_hdr[7:].strip()
            try:
                payload = jwt_service.decode_token(token, "access")
                sid_str = payload.get("sid")
                if sid_str:
                    sid = uuid.UUID(sid_str)
                    with _get_db_session(request) as db:
                        session = db.get(UserSession, sid)
                        if session and session.status == SessionStatus.ACTIVE:
                            if session.ecdsa_pubkey and session.ecdsa_pubkey != pubkey.strip():
                                ip = client_ip(request)
                                logger.error(
                                    "SESSION HIJACK DETECTED | session=%s user=%s ip=%s (pubkey mismatch)",
                                    sid,
                                    session.user_id,
                                    ip,
                                )

                                # Log Critical Security Alert
                                alert = Alert(
                                    user_id=session.user_id,
                                    session_id=session.id,
                                    severity=AlertSeverity.CRITICAL,
                                    status=AlertStatus.OPEN,
                                    category="session_hijack",
                                    title=f"Session Hijack Attempt for User {session.user_id}",
                                    description=(
                                        f"A valid session token was presented from IP {ip} with a "
                                        f"device public key that does NOT match the registered device key. "
                                        f"Possible stolen token or cookie attack."
                                    ),
                                    trust_score=15.0,
                                    evidence={
                                        "ip_address": ip,
                                        "session_id": str(sid),
                                        "registered_pubkey": session.ecdsa_pubkey[:16] + "...",
                                        "presented_pubkey": pubkey[:16] + "...",
                                        "path": path,
                                    },
                                )
                                db.add(alert)
                                db.commit()

                                return JSONResponse(
                                    status_code=401,
                                    content={
                                        "detail": "Session hijacked: device key mismatch. Token used from unauthorized machine.",
                                        "code": "session_hijack",
                                    },
                                    headers={"X-Device-Binding": "HIJACK_BLOCKED"},
                                )
            except Exception:
                pass

        response = await call_next(request)
        if pubkey and sig:
            response.headers["X-Device-Bound"] = "ECDSA-P256"
        return response

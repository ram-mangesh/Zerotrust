"""ECDSA P-256 WebCrypto signature verification.

Handles client-side hardware-bound signatures generated by the browser's
WebCrypto API (`crypto.subtle.sign`).

WebCrypto emits signatures in raw IEEE P1363 format (64-byte concatenation of
`r || s`), whereas Python's `cryptography` library expects ASN.1 DER format.
This module translates between P1363 and DER to verify request authenticity.
"""

from __future__ import annotations

import base64
import logging

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils

logger = logging.getLogger(__name__)


def verify_ecdsa_signature(
    public_key_b64: str,
    message: str,
    signature_b64: str,
) -> bool:
    """Verify an ECDSA P-256 (SECP256R1) signature from WebCrypto API."""
    try:
        # Decode 65-byte uncompressed public key point (0x04 || X || Y)
        pub_bytes = base64.b64decode(public_key_b64.strip())
        public_key = ec.EllipticCurvePublicKey.from_encoded_point(
            ec.SECP256R1(), pub_bytes
        )

        sig_bytes = base64.b64decode(signature_b64.strip())

        # If 64 bytes raw (P-256 IEEE P1363: 32 bytes r + 32 bytes s), convert to ASN.1 DER
        if len(sig_bytes) == 64:
            r = int.from_bytes(sig_bytes[:32], "big")
            s = int.from_bytes(sig_bytes[32:], "big")
            der_signature = utils.encode_dss_signature(r, s)
        else:
            der_signature = sig_bytes

        # Verify signature with SHA-256
        public_key.verify(
            der_signature,
            message.encode("utf-8"),
            ec.ECDSA(hashes.SHA256()),
        )
        return True
    except (InvalidSignature, Exception) as exc:
        logger.debug("ECDSA verification failed: %s", exc)
        return False


def generate_test_keypair() -> tuple[str, ec.EllipticCurvePrivateKey]:
    """Generate a test ECDSA P-256 key pair and return (b64_pubkey, private_key)."""
    priv_key = ec.generate_private_key(ec.SECP256R1())
    pub_point = priv_key.public_key().public_bytes(
        encoding=serialization.Encoding.X962,
        format=serialization.PublicFormat.UncompressedPoint,
    )
    return base64.b64encode(pub_point).decode("utf-8"), priv_key


def sign_message_p1363(private_key: ec.EllipticCurvePrivateKey, message: str) -> str:
    """Sign message and return Base64 IEEE P1363 signature (64 bytes raw r||s, like WebCrypto)."""
    der_sig = private_key.sign(message.encode("utf-8"), ec.ECDSA(hashes.SHA256()))
    r, s = utils.decode_dss_signature(der_sig)
    raw_sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    return base64.b64encode(raw_sig).decode("utf-8")
